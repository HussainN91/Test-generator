"""Offline: generate items through the Claude API and stage them for review.

This is the only command that costs money, and it is never run by the deployed
app — see the module docstring in bank/generation/claude_pipeline.py.

    export ANTHROPIC_API_KEY=...          # or: ant auth login
    python manage.py generate_items --grade 10 --unit 3 --type gap_fill --count 8
    python manage.py generate_items --grade 10 --all-units --type gap_fill
    python manage.py generate_items --grade 10 --unit 3 --dry-run   # print, write nothing

Generated items land as DRAFT (or FLAGGED if the review pass objected) and are
invisible to teachers until an admin approves them in the review queue.
"""

from __future__ import annotations

import hashlib
import json

from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from bank.generation.claude_pipeline import (
    DEFAULT_BATCH_SIZE,
    PipelineUnavailable,
    generate_reviewed_items,
)
from bank.models import Item, QuestionType, ReviewStatus
from content.models import Unit, VocabularyEntry

#: Question types the pipeline can write. The other two are derived offline
#: without an LLM by `seed_bank`.
PIPELINE_TYPES = [
    QuestionType.GAP_FILL,
    QuestionType.WORD_FORMATION,
    QuestionType.KEY_WORD_TRANSFORMATION,
    QuestionType.ERROR_CORRECTION,
]

#: Which payload field carries the answer, per question type.
ANSWER_FIELDS = {
    QuestionType.GAP_FILL: "target_word",
    QuestionType.WORD_FORMATION: "correct_form",
    QuestionType.ERROR_CORRECTION: "corrected_word_phrase",
}


class Command(BaseCommand):
    help = "Generate item-bank entries with Claude (offline; requires an API key)."

    def add_arguments(self, parser):
        parser.add_argument("--grade", type=int, required=True)
        parser.add_argument("--unit", type=int, action="append", dest="units")
        parser.add_argument("--all-units", action="store_true")
        parser.add_argument(
            "--type", action="append", dest="types",
            help=f"One of: {', '.join(t.value for t in PIPELINE_TYPES)}. Repeatable.",
        )
        parser.add_argument("--count", type=int, default=DEFAULT_BATCH_SIZE)
        parser.add_argument("--batch-label", type=str, default="")
        parser.add_argument("--dry-run", action="store_true")

    def handle(self, *args, **options):
        units = Unit.objects.filter(grade__number=options["grade"]).select_related("grade")
        if options["units"]:
            units = units.filter(number__in=options["units"])
        elif not options["all_units"]:
            raise CommandError("Pass --unit N (repeatable) or --all-units.")
        units = list(units.order_by("number"))
        if not units:
            raise CommandError("No matching units. Run import_guide first.")

        types = options["types"] or [QuestionType.GAP_FILL]
        for question_type in types:
            if question_type not in [t.value for t in PIPELINE_TYPES]:
                raise CommandError(
                    f"'{question_type}' is not generated by this pipeline. "
                    f"Choose from: {', '.join(t.value for t in PIPELINE_TYPES)}"
                )

        label = options["batch_label"] or f"claude-g{options['grade']}"
        written = rejected = 0

        for unit in units:
            if not unit.vocabulary.exists():
                self.stdout.write(self.style.WARNING(f"Unit {unit.number}: no vocabulary, skipping."))
                continue

            for question_type in types:
                self.stdout.write(f"Unit {unit.number} · {question_type} …", ending=" ")
                try:
                    results = generate_reviewed_items(unit, question_type, options["count"])
                except PipelineUnavailable as error:
                    raise CommandError(str(error)) from error

                accepted = [r for r in results if r.accepted]
                self.stdout.write(f"{len(accepted)}/{len(results)} passed review")

                for result in results:
                    if not result.accepted:
                        rejected += 1
                        self.stdout.write(
                            self.style.WARNING(f"    rejected — {result.review_problem}")
                        )

                if options["dry_run"]:
                    for result in accepted:
                        self.stdout.write("    " + json.dumps(result.fields, ensure_ascii=False))
                    written += len(accepted)
                    continue

                written += self._write(unit, question_type, results, label)

        verb = "Would write" if options["dry_run"] else "Wrote"
        self.stdout.write(
            self.style.SUCCESS(f"{verb} {written} items; {rejected} rejected by the review pass.")
        )
        if not options["dry_run"]:
            self.stdout.write(
                "Next: python manage.py validate_items --status draft, "
                "then approve what survives in the admin review queue."
            )

    def _write(self, unit, question_type, results, label) -> int:
        payloads = []
        for result in results:
            fields = dict(result.fields)
            answer_field = ANSWER_FIELDS.get(question_type)
            if answer_field:
                answer = fields.get(answer_field, "")
                acceptable = []
            else:
                acceptable = fields.get("acceptable_answers", [])
                answer = acceptable[0] if acceptable else ""

            digest = hashlib.sha256(
                json.dumps(
                    {"u": unit.pk, "t": question_type, "f": fields}, sort_keys=True, ensure_ascii=False
                ).encode("utf-8")
            ).hexdigest()

            payloads.append(
                Item(
                    unit=unit,
                    grammar_point=getattr(unit, "grammar_point", None),
                    target_vocabulary=self._match_vocabulary(unit, answer),
                    question_type=question_type,
                    payload=fields,
                    model_answer=answer,
                    acceptable_answers=acceptable,
                    review_status=ReviewStatus.DRAFT if result.accepted else ReviewStatus.FLAGGED,
                    review_notes=result.review_problem or "Passed the LLM review pass.",
                    generation_batch=label,
                    content_hash=digest,
                )
            )

        existing = set(Item.objects.filter(unit=unit).values_list("content_hash", flat=True))
        fresh = [p for p in payloads if p.content_hash not in existing]
        with transaction.atomic():
            Item.objects.bulk_create(fresh, ignore_conflicts=True)
        return len(fresh)

    @staticmethod
    def _match_vocabulary(unit, answer: str) -> VocabularyEntry | None:
        if not answer:
            return None
        return unit.vocabulary.filter(word__iexact=answer.strip()).first()
